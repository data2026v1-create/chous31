interface I18nValue {
  locale: Locale;
  dir: "ltr" | "rtl";
  setLocale: (l: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    try {
      return localStorage.getItem("stepstore_lang") === "ar" ? "ar" : "fr";
    } catch {
      return "fr";
    }
  });

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    try {
      localStorage.setItem("stepstore_lang", locale);
    } catch {
      /* ignore */
    }
  }, [locale]);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let raw = dict[locale][key] ?? dict.fr[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          raw = raw.split(`{${k}}`).join(String(v));
        }
      }
      return raw;
    },
    [locale]
  );

  const value: I18nValue = {
    locale,
    dir: locale === "ar" ? "rtl" : "ltr",
    setLocale: setLocaleState,
    t,
  };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n doit être utilisé dans <I18nProvider>");
  return ctx;
}

/** Choisit le texte selon la locale (fr par défaut, ar en repli) */
export function tr(locale: Locale, fr: string, ar?: string): string {
  return locale === "ar" && ar ? ar : fr;
}
